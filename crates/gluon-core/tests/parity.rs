//! Stage 1+2 parity: an equivalent `gluon.rs` and `gluon.rhai` must
//! produce identical `BuildModel` values for every fixture under
//! `tests/fixtures/`.  Deleted in Stage 3 when Rhai goes away.

use gluon_core::{evaluate, load_build_model};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Resolve `<workspace>/tests/fixtures/<name>` from this crate.
fn fixture_dir(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/gluon-core has a two-level parent")
        .join("tests")
        .join("fixtures")
        .join(name)
}

/// Recursive copy. Hand-rolled to avoid pulling in fs_extra for tests.
fn copy_dir_all(src: &Path, dst: &Path) -> io::Result<()> {
    fs::create_dir_all(dst)?;
    for entry in fs::read_dir(src)? {
        let entry = entry?;
        let ty = entry.file_type()?;
        let from = entry.path();
        let to = dst.join(entry.file_name());
        if ty.is_dir() {
            copy_dir_all(&from, &to)?;
        } else if ty.is_file() {
            fs::copy(&from, &to)?;
        }
    }
    Ok(())
}

/// Recursively remove all `"span"` keys from a JSON value.
///
/// Source spans are file-path-specific debug metadata generated by the
/// Rhai engine but not yet by the gluon.rs path. They carry no
/// semantic content — strip before comparing the two models. When
/// the gluon.rs path gains span support in a later stage this
/// normalisation step can be revisited.
fn strip_spans(v: &mut serde_json::Value) {
    match v {
        serde_json::Value::Object(map) => {
            map.remove("span");
            for val in map.values_mut() {
                strip_spans(val);
            }
        }
        serde_json::Value::Array(arr) => {
            for val in arr.iter_mut() {
                strip_spans(val);
            }
        }
        _ => {}
    }
}

/// Asserts the on-disk `<fixture>/gluon.rhai` and
/// `<fixture>/gluon.rs` produce structurally-identical
/// `BuildModel`s (modulo `span` fields, which Rhai records and the
/// Rust DSL does not yet).
///
/// Strategy:
/// 1. Evaluate the `.rhai` file directly from the source tree (no
///    side effects in the source dir — `evaluate` only reads).
/// 2. Copy the fixture to a tempdir, delete every `gluon*.rhai`
///    sibling so `load_build_model` unambiguously picks the `.rs`,
///    then run it through the script-runner pipeline.
/// 3. Strip `span` keys from both JSON forms and compare.
#[allow(dead_code)]
fn assert_fixture_parity(name: &str) {
    if gluon_core::RustcInfo::probe().is_err() {
        eprintln!("skipping {name}: rustc probe failed");
        return;
    }
    let src = fixture_dir(name);
    assert!(
        src.join("gluon.rhai").is_file(),
        "fixture {src:?} is missing gluon.rhai"
    );
    assert!(
        src.join("gluon.rs").is_file(),
        "fixture {src:?} is missing gluon.rs (Stage 2 conversion incomplete)"
    );

    let rhai_model = evaluate(&src.join("gluon.rhai")).unwrap_or_else(|e| {
        panic!(
            "evaluate({:?}/gluon.rhai) failed: {e}",
            src.file_name().unwrap()
        )
    });

    let tmp = tempfile::tempdir().expect("create tempdir");
    copy_dir_all(&src, tmp.path()).expect("copy fixture");
    // Remove every `gluon*.rhai` so load_build_model unambiguously
    // picks the .rs path. Without this, `gluon.rs` already wins —
    // but defending against the precedence rule changing later costs
    // nothing.
    for entry in fs::read_dir(tmp.path()).unwrap() {
        let entry = entry.unwrap();
        let p = entry.path();
        let fname = match p.file_name().and_then(|s| s.to_str()) {
            Some(s) => s.to_string(),
            None => continue,
        };
        if fname.starts_with("gluon") && fname.ends_with(".rhai") {
            fs::remove_file(&p).unwrap();
        }
    }
    let rs_model = load_build_model(tmp.path())
        .unwrap_or_else(|e| panic!("load_build_model({:?}) failed: {e}", tmp.path()));

    let mut a = serde_json::to_value(&rhai_model).unwrap();
    let mut b = serde_json::to_value(&rs_model).unwrap();
    strip_spans(&mut a);
    strip_spans(&mut b);
    assert_eq!(
        a, b,
        "fixture {name}: rhai and rs BuildModels differ (spans excluded)"
    );
}

/// Parity check for fixtures that ship a non-default .rhai/.rs pair
/// (e.g. vendor-minimal's `gluon.path-only.*`). Same strategy as
/// `assert_fixture_parity` but the file names are explicit.
#[allow(dead_code)]
fn assert_fixture_parity_named(fixture: &str, rhai_filename: &str, rs_filename: &str) {
    if gluon_core::RustcInfo::probe().is_err() {
        eprintln!("skipping {fixture}/{rs_filename}: rustc probe failed");
        return;
    }
    let src = fixture_dir(fixture);
    let rhai_path = src.join(rhai_filename);
    let rs_path = src.join(rs_filename);
    assert!(rhai_path.is_file(), "missing {rhai_path:?}");
    assert!(rs_path.is_file(), "missing {rs_path:?}");

    let rhai_model = evaluate(&rhai_path).unwrap();

    // For the rs side, copy the fixture into a tempdir and rename
    // `<rs_filename>` to `gluon.rs` so load_build_model picks it up.
    // Also delete every other gluon*.rhai/rs sibling so the harness
    // doesn't pick the default by accident.
    let tmp = tempfile::tempdir().unwrap();
    copy_dir_all(&src, tmp.path()).unwrap();
    for entry in fs::read_dir(tmp.path()).unwrap() {
        let entry = entry.unwrap();
        let p = entry.path();
        let fname = match p.file_name().and_then(|s| s.to_str()) {
            Some(s) => s.to_string(),
            None => continue,
        };
        if fname.starts_with("gluon")
            && (fname.ends_with(".rhai") || fname.ends_with(".rs"))
            && fname != rs_filename
        {
            fs::remove_file(&p).unwrap();
        }
    }
    fs::rename(tmp.path().join(rs_filename), tmp.path().join("gluon.rs")).unwrap();
    let rs_model = load_build_model(tmp.path()).unwrap();

    let mut a = serde_json::to_value(&rhai_model).unwrap();
    let mut b = serde_json::to_value(&rs_model).unwrap();
    strip_spans(&mut a);
    strip_spans(&mut b);
    assert_eq!(
        a, b,
        "fixture {fixture}/{rs_filename}: rhai and rs differ"
    );
}

/// Stage-1 inline-string smoke test, kept so a regression in the
/// script-runner pipeline shows up even when no fixture has been
/// ported yet. Will be deleted in Stage 3 alongside Rhai.
#[test]
#[ignore]
fn rs_and_rhai_inline_smoke() {
    if gluon_core::RustcInfo::probe().is_err() {
        eprintln!("skipping: rustc probe failed");
        return;
    }
    const RHAI: &str = r#"
project("demo", "0.1.0");
target("x86_64-unknown-none");
profile("dev").target("x86_64-unknown-none").opt_level(0).debug_info(true);
"#;
    const RS: &str = r#"
fn main() -> gluon_config::Result<()> {
    let mut cfg = gluon_config::Config::new();
    cfg.project("demo", "0.1.0");
    let t = cfg.target("x86_64-unknown-none");
    cfg.profile("dev").target(t).opt_level(0).debug_info(true);
    cfg.emit()
}
"#;
    let rhai_dir = tempfile::tempdir().unwrap();
    fs::write(rhai_dir.path().join("gluon.rhai"), RHAI).unwrap();
    let rhai_model = evaluate(&rhai_dir.path().join("gluon.rhai")).unwrap();

    let rs_dir = tempfile::tempdir().unwrap();
    fs::write(rs_dir.path().join("gluon.rs"), RS).unwrap();
    let rs_model = load_build_model(rs_dir.path()).unwrap();

    let mut a = serde_json::to_value(&rhai_model).unwrap();
    let mut b = serde_json::to_value(&rs_model).unwrap();
    strip_spans(&mut a);
    strip_spans(&mut b);
    assert_eq!(a, b);
}

/// Confirms `gluon.rs` wins over `gluon.rhai` when both exist. This
/// is a property of `load_build_model`, not a fixture parity check
/// — keep it inline.
#[test]
#[ignore]
fn rs_wins_over_rhai_when_both_exist() {
    if gluon_core::RustcInfo::probe().is_err() {
        eprintln!("skipping: rustc probe failed");
        return;
    }
    let dir = tempfile::tempdir().unwrap();
    fs::write(
        dir.path().join("gluon.rhai"),
        r#"project("from-rhai", "0.1.0");"#,
    )
    .unwrap();
    fs::write(
        dir.path().join("gluon.rs"),
        r#"
fn main() -> gluon_config::Result<()> {
    let mut cfg = gluon_config::Config::new();
    cfg.project("from-rs", "0.1.0");
    cfg.emit()
}
"#,
    )
    .unwrap();
    let model = load_build_model(dir.path()).unwrap();
    assert_eq!(model.project.unwrap().name, "from-rs");
}
