//! Stage 1 parity: an equivalent `gluon.rs` and `gluon.rhai` must produce
//! identical `BuildModel` values. Deleted in Stage 3 when Rhai goes away.

use gluon_core::{evaluate, load_build_model};
use std::fs;

// Fixtures are intentionally minimal — no crates or groups, no boot_binary
// (which requires a declared crate). The goal is to verify that project,
// target, and profile round-trip identically through both paths.
const RHAI_FIXTURE: &str = r#"
project("demo", "0.1.0");
target("x86_64-unknown-none");
profile("dev")
    .target("x86_64-unknown-none")
    .opt_level(0)
    .debug_info(true);
"#;

const RS_FIXTURE: &str = r#"
fn main() -> gluon_config::Result<()> {
    let mut cfg = gluon_config::Config::new();
    cfg.project("demo", "0.1.0");
    let t = cfg.target("x86_64-unknown-none");
    cfg.profile("dev")
        .target(t)
        .opt_level(0)
        .debug_info(true);
    cfg.emit()
}
"#;

/// Recursively remove all `"span"` keys from a JSON value.
///
/// Source spans are file-path-specific debug metadata generated by the Rhai
/// engine but not yet by the gluon.rs path (no AST span tracking yet). They
/// carry no semantic content, so we strip them before comparing the two
/// models. When the gluon.rs path gains span support in a later stage this
/// normalisation step can be revisited.
fn strip_spans(v: &mut serde_json::Value) {
    match v {
        serde_json::Value::Object(map) => {
            map.remove("span");
            for val in map.values_mut() {
                strip_spans(val);
            }
        }
        serde_json::Value::Array(arr) => {
            for val in arr.iter_mut() {
                strip_spans(val);
            }
        }
        _ => {}
    }
}

#[test]
#[ignore]
fn rs_and_rhai_produce_identical_build_model() {
    if gluon_core::RustcInfo::probe().is_err() {
        eprintln!("skipping: rustc probe failed");
        return;
    }

    let rhai_dir = tempfile::tempdir().unwrap();
    fs::write(rhai_dir.path().join("gluon.rhai"), RHAI_FIXTURE).unwrap();
    let rhai_model = evaluate(&rhai_dir.path().join("gluon.rhai")).unwrap();

    let rs_dir = tempfile::tempdir().unwrap();
    fs::write(rs_dir.path().join("gluon.rs"), RS_FIXTURE).unwrap();
    let rs_model = load_build_model(rs_dir.path()).unwrap();

    let mut rhai_json = serde_json::to_value(&rhai_model).unwrap();
    let mut rs_json = serde_json::to_value(&rs_model).unwrap();
    // Spans embed source file paths and are not produced by the gluon.rs path
    // yet — strip them before comparing semantic content.
    strip_spans(&mut rhai_json);
    strip_spans(&mut rs_json);
    assert_eq!(
        rhai_json, rs_json,
        "gluon.rs and gluon.rhai must produce identical BuildModel JSON (spans excluded)"
    );
}

#[test]
#[ignore]
fn rs_wins_over_rhai_when_both_exist() {
    if gluon_core::RustcInfo::probe().is_err() {
        eprintln!("skipping: rustc probe failed");
        return;
    }
    let dir = tempfile::tempdir().unwrap();
    // Different project names so we can detect which one was loaded.
    fs::write(
        dir.path().join("gluon.rhai"),
        r#"project("from-rhai", "0.1.0");"#,
    )
    .unwrap();
    fs::write(
        dir.path().join("gluon.rs"),
        r#"
fn main() -> gluon_config::Result<()> {
    let mut cfg = gluon_config::Config::new();
    cfg.project("from-rs", "0.1.0");
    cfg.emit()
}
"#,
    )
    .unwrap();
    let model = load_build_model(dir.path()).unwrap();
    assert_eq!(
        model.project.unwrap().name,
        "from-rs",
        "gluon.rs must win when both exist"
    );
}
