//! Per-`quon.rs` script binary cache.
//!
//! ## What this caches
//!
//! Compiling a user's `quon.rs` with rustc takes ~1–2s on a warm
//! quon-config rlib. Running it takes ~50ms. We cache the compiled
//! binary so subsequent `quon build` invocations skip rustc entirely.
//!
//! ## Cache key
//!
//! `sha256(rustc_version || wrapper || hash(quon.rs) ||
//! hash(quon_config_rlib) || hash(quon_config_rmeta))`, the last
//! only when cargo wrote one, where `hash` is the file content hash
//! of [`crate::cache::hash_file`]
//!
//! - `rustc_version` covers "the user upgraded their toolchain".
//! - `wrapper` is the generated `main.rs` (see [`wrapper_source`]), so a
//!   quon that generates a different one recompiles every script.
//! - The script-source hash covers any edit to `quon.rs`.
//! - The rlib and rmeta hashes cover a rebuild of `quon-config`
//!   (which would change ABI/layout and require relinking the script).
//!
//! Anything outside those inputs — env vars, working directory, etc. —
//! does NOT invalidate. That's deliberate: those don't affect the
//! compiled binary's behaviour. Re-running a cached binary is free, so
//! the cost of a missed invalidation is bounded.
//!
//! ## What's not cached
//!
//! Stderr from rustc on a *successful* compile is discarded. On
//! failure we surface the full stderr verbatim through `Error::Config`,
//! plus a migration hint when the script is written for the old API.
//! There is no diagnostic-level structured-error path yet — Stage 4
//! may upgrade this to parse `--error-format=json` and emit
//! `Error::Diagnostics`.

use crate::compile::RustcInfo;
use crate::error::{Error, Result};
use crate::script_runner::file_hashes::FileHashes;
use crate::script_runner::rlib::RlibPaths;
use std::path::{Path, PathBuf};

/// Compile `script_path` into a binary cached under
/// `<build_dir>/script-runner/scripts/<key>/quon_script[.exe]`.
/// Returns the path to the binary (cached or freshly built).
///
/// `quon.rs` defines `pub fn config(q: &mut Quon) -> Result<()>`
/// and no `main`. The binary's crate root is a generated `main.rs` in
/// the entry dir that includes the script as a module and calls it.
///
/// The lookup is two-tier: the outer directory is keyed by
/// `entrypoint + rustc + rlib` (cheap to recompute on every invocation),
/// and the inner check verifies that the on-disk transitive fingerprint
/// still matches the current hash of every file the script's depfile
/// lists. The fingerprint catches edits to files reached via `mod` /
/// `#[path]` from the entrypoint, which would otherwise leave the outer
/// key unchanged, so both layers are needed.
pub(crate) fn ensure_script_binary(
    script_path: &Path,
    build_dir: &Path,
    rustc_info: &RustcInfo,
    rlib: &RlibPaths,
    hashes: &mut FileHashes,
) -> Result<PathBuf> {
    let cache_root = build_dir.join("script-runner").join("scripts");
    let mut quon_config_files = vec![rlib.quon_config_rlib.as_path()];
    quon_config_files.extend(rlib.quon_config_rmeta.as_deref());
    let wrapper = wrapper_source(script_path)?;
    let key = compute_key(
        script_path,
        &wrapper,
        &rustc_info.version,
        &quon_config_files,
        hashes,
    )?;
    let entry_dir = cache_root.join(&key);
    let bin_path = entry_dir.join(SCRIPT_BIN_NAME);

    if entry_dir.is_dir() && lookup_cached_binary(&entry_dir)? {
        return Ok(bin_path);
    }

    std::fs::create_dir_all(&entry_dir).map_err(|e| Error::Io {
        path: entry_dir.clone(),
        source: e,
    })?;
    let main_rs = entry_dir.join("main.rs");
    std::fs::write(&main_rs, &wrapper).map_err(|e| Error::Io {
        path: main_rs.clone(),
        source: e,
    })?;
    compile_script(script_path, &main_rs, &entry_dir, rustc_info, rlib)?;
    write_transitive_fingerprint(&entry_dir)?;
    Ok(bin_path)
}

/// The generated crate root for `script_path`.
///
/// `#[path]` with the absolute path keeps rustc's diagnostics pointing
/// at the user's `quon.rs`, and a file loaded through `#[path]`
/// resolves its own `mod` and `#[path]` items relative to its own
/// directory, as it did when it was the crate root. A returned error
/// reaches `main`'s `Result`, which prints it to stderr and exits
/// non-zero.
fn wrapper_source(script_path: &Path) -> Result<String> {
    let path = script_path.to_str().ok_or_else(|| {
        Error::Config(format!(
            "quon.rs path is not valid UTF-8: {}",
            script_path.display()
        ))
    })?;
    Ok(format!(
        "// Generated by quon: the crate root for {path:?}.\n\
         #[path = {path:?}]\n\
         mod script;\n\
         \n\
         fn main() -> quon_config::Result<()> {{\n    \
             let mut q = quon_config::Quon::connected();\n    \
             script::config(&mut q)?;\n    \
             q.emit()\n\
         }}\n"
    ))
}

